-- Restore public Meta Ad Library discovery queue for Social Edition.
create table if not exists public.social_discovery_queries (
 id bigint generated by default as identity primary key, query_text text not null unique,
 query_type text not null default 'KEYWORD', country text not null default 'Iraq',
 source text not null default 'META_AD_LIBRARY', enabled boolean not null default true,
 priority integer not null default 50, last_used_at timestamptz, run_count integer not null default 0,
 hit_count integer not null default 0, last_hit_count integer not null default 0,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.social_discovery_runs (
 id bigint generated by default as identity primary key, run_date date not null default current_date,
 country text not null default 'Iraq', source text not null default 'META_AD_LIBRARY',
 status text not null default 'RUNNING', queries_used jsonb not null default '[]'::jsonb,
 advertisers_found integer not null default 0, candidates_created integer not null default 0,
 candidates_updated integer not null default 0, completed_at timestamptz, notes text,
 started_at timestamptz not null default now()
);
create table if not exists public.social_discovery_candidates (
 id bigint generated by default as identity primary key, page_id_external text not null unique,
 page_name text, platform text not null default 'FACEBOOK', country text not null default 'Iraq',
 profile_url text, ad_library_url text, landing_url text, phone text, whatsapp text,
 discovery_query text, evidence_source text, active_ads_count integer not null default 0,
 ads jsonb not null default '[]'::jsonb, evidence jsonb not null default '[]'::jsonb,
 health_score numeric, development_need_score numeric, qualification_score numeric,
 audit_status text not null default 'PENDING', first_seen_at timestamptz not null default now(),
 last_seen_at timestamptz not null default now(), created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists social_discovery_candidates_recent_idx on public.social_discovery_candidates(last_seen_at desc);
create index if not exists social_discovery_candidates_audit_idx on public.social_discovery_candidates(audit_status,last_seen_at desc);
alter table public.social_discovery_queries enable row level security;
alter table public.social_discovery_runs enable row level security;
alter table public.social_discovery_candidates enable row level security;
drop policy if exists "Authenticated can read social discovery queries" on public.social_discovery_queries;
create policy "Authenticated can read social discovery queries" on public.social_discovery_queries for select to authenticated using (true);
drop policy if exists "Authenticated can read social discovery runs" on public.social_discovery_runs;
create policy "Authenticated can read social discovery runs" on public.social_discovery_runs for select to authenticated using (true);
drop policy if exists "Authenticated can read social discovery candidates" on public.social_discovery_candidates;
create policy "Authenticated can read social discovery candidates" on public.social_discovery_candidates for select to authenticated using (true);
